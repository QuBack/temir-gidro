def kit_points(model):
    """Kit items with their marker position on the kit image, in the image's own pixels
    (an SVG overlay with the image's viewBox; CSP forbids inline styles). pos is None
    for items not visible on the picture — they stay in the list only."""
    image = model["kit_image"]
    w, h = image["size"] if image else (0, 0)
    markers = {i: (round(x * w / 100), round(y * h / 100)) for i, x, y in model["kit_markers"]}
    return [
        {"title": title, "text": text, "icon": icon, "pos": markers.get(i)}
        for i, (title, text, icon) in enumerate(model["kit"])
    ]


def kit_overlay(model):
    """viewBox size and marker radius for the kit overlay; markers keep one on-screen size per picture."""
    image = model["kit_image"]
    if not image:
        return None
    w, h = image["size"]
    r = round(max(w, h) * 0.034)
    # The icon inside a marker: a square of side `is`, offset by `ix` from the centre.
    size = round(r * 1.2)
    return {"w": w, "h": h, "r": r, "is": size, "ix": -size // 2}


