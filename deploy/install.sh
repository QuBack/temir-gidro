#!/usr/bin/env bash
# Install the TEMIR GIDRO site on a fresh Ubuntu 22.04/24.04 or Debian 12 server.
#
#   With a domain (HTTPS from Let's Encrypt; DNS A record must already point here):
#     sudo bash deploy/install.sh --domain temir-gidro.com
#   Demo by IP, plain HTTP, closed from search engines:
#     sudo bash deploy/install.sh
#   A domain, but closed from search engines (staging):
#     sudo bash deploy/install.sh --domain test.temir-gidro.com --staging
#
# Safe to run again: it keeps the existing .env (secrets, database password) and
# only rebuilds and restarts the containers. Later updates: deploy/update.sh.
set -euo pipefail

REPO_URL="https://github.com/QuBack/temir-gidro.git"
BRANCH="main"
APP_DIR="/opt/temir-gidro"
DOMAIN=""
STAGING=0

usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --domain) DOMAIN="${2:?}"; shift 2 ;;
    --staging) STAGING=1; shift ;;
    --repo) REPO_URL="${2:?}"; shift 2 ;;
    --branch) BRANCH="${2:?}"; shift 2 ;;
    --dir) APP_DIR="${2:?}"; shift 2 ;;
    -h|--help) usage ;;
    *) echo "Неизвестный параметр: $1" >&2; usage 1 ;;
  esac
done

say() { printf '\n\033[1;31m>>>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mОшибка:\033[0m %s\n' "$*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "запустите через sudo"
[ -r /etc/os-release ] || die "не удалось определить систему"
. /etc/os-release
case "$ID" in ubuntu|debian) ;; *) die "поддерживаются Ubuntu и Debian, а это: $ID" ;; esac

# ---------- 1. Docker from the official repository ----------
if ! docker compose version >/dev/null 2>&1; then
  say "Устанавливаю Docker"
  apt-get update -qq
  apt-get install -y -qq ca-certificates curl git openssl >/dev/null
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/$ID/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] \
https://download.docker.com/linux/$ID ${VERSION_CODENAME} stable" > /etc/apt/sources.list.d/docker.list
  apt-get update -qq
  apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >/dev/null
  systemctl enable --now docker
else
  apt-get install -y -qq git openssl curl >/dev/null 2>&1 || true
fi

# ---------- 2. The code ----------
# Run from inside a checkout → use it; otherwise clone into APP_DIR.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-.}")" && pwd)"
if [ -f "$SCRIPT_DIR/../manage.py" ]; then
  APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
elif [ -d "$APP_DIR/.git" ]; then
  say "Обновляю код в $APP_DIR"
  git -C "$APP_DIR" pull --ff-only
else
  say "Скачиваю код в $APP_DIR"
  git clone --branch "$BRANCH" "$REPO_URL" "$APP_DIR"
fi
cd "$APP_DIR"

# ---------- 3. Settings (.env), generated once ----------
SERVER_IP="$(curl -fsS4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
if [ ! -f .env ]; then
  say "Создаю .env с новыми паролями"
  rand() { openssl rand -base64 96 | tr -dc 'A-Za-z0-9' | head -c "$1"; }
  if [ -n "$DOMAIN" ]; then
    SITE_URL="https://$DOMAIN"; HOSTS="$DOMAIN,www.$DOMAIN"; HTTPS=True; CADDYFILE=deploy/Caddyfile
  else
    SITE_URL="http://$SERVER_IP"; HOSTS="$SERVER_IP"; HTTPS=False; CADDYFILE=deploy/Caddyfile.ip
  fi
  # A demo by IP or a staging server must not get into the search index.
  INDEXING=True
  if [ "$STAGING" -eq 1 ] || [ -z "$DOMAIN" ]; then INDEXING=False; fi
  cat > .env <<EOF
# Generated by deploy/install.sh on $(date -u +%Y-%m-%d). Never commit this file.
DEBUG=False
SECRET_KEY=$(rand 60)
POSTGRES_PASSWORD=$(rand 32)
SITE_DOMAIN=${DOMAIN:-localhost}
SITE_URL=$SITE_URL
ALLOWED_HOSTS=$HOSTS,localhost
HTTPS=$HTTPS
CADDYFILE=$CADDYFILE
SITE_LANGUAGES=ru
ADMIN_URL=manage-$(rand 6 | tr 'A-Z' 'a-z')/
SEO_INDEXING=$INDEXING
YANDEX_VERIFICATION=
GOOGLE_VERIFICATION=
YANDEX_METRIKA_ID=
TELEGRAM_BOT_TOKEN=
TELEGRAM_CHAT_ID=
EOF
  chmod 600 .env
else
  say "Файл .env уже есть — оставляю как есть"
fi

# ---------- 4. Firewall ----------
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  say "Открываю порты 80 и 443 в ufw"
  ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 443/udp >/dev/null
fi

# ---------- 5. Build and start ----------
COMPOSE=(docker compose -f compose.yml -f deploy/compose.prod.yml)
say "Собираю и запускаю контейнеры (первый раз — несколько минут)"
"${COMPOSE[@]}" up -d --build --remove-orphans

say "Жду, пока сайт ответит"
URL="$(grep '^SITE_URL=' .env | cut -d= -f2-)"
for _ in $(seq 1 60); do
  CODE="$(curl -ks -o /dev/null -w '%{http_code}' --resolve "${URL#*://}:80:127.0.0.1" --resolve "${URL#*://}:443:127.0.0.1" "$URL/" || true)"
  [ "$CODE" = "200" ] && break
  sleep 3
done
[ "${CODE:-}" = "200" ] || { "${COMPOSE[@]}" logs --tail 50 web; die "сайт не отвечает (код ${CODE:-нет}), логи выше"; }

ADMIN="$(grep '^ADMIN_URL=' .env | cut -d= -f2-)"
cat <<EOF

  Готово. Сайт: $URL/
  Админка (заявки): $URL/$ADMIN
  Папка проекта: $APP_DIR

  Создать пользователя для админки:
    cd $APP_DIR && ${COMPOSE[*]} exec web python manage.py createsuperuser

  Обновить сайт после изменений в репозитории:
    sudo bash $APP_DIR/deploy/update.sh

EOF
